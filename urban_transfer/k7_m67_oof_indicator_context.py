"""M6.7: leak-free source-task predictive context by source-city cross fitting.

Source Population/Food labels only. OOF predictions for *all images*
belonging to source-fit cities are generated by a fold model that excluded
their entire city. Other cities (including source city-held validation)
use models fitted only on source-fit cities. All image rows have two
continuous standardized predicted source indicators, never true outcomes.
"""
import hashlib
import json
import os
from pathlib import Path

import numpy as np
import torch


def crossfit_source_indicator_predictions(frame,visual,geo,y,names,
                                          train_ids,stats,folds=4,seed=42,
                                          alpha=100.):
    from sklearn.model_selection import GroupKFold
    from sklearn.pipeline import make_pipeline
    from sklearn.preprocessing import StandardScaler
    from sklearn.linear_model import Ridge
    from urban_transfer.k7_m1_knowledge import TRAIN_TASKS

    ids=np.asarray(train_ids,dtype=np.int64)
    if not np.isin(np.asarray(names,dtype=str)[ids],TRAIN_TASKS).all():
        raise ValueError("Cross-fit labels must be source training tasks only")
    cities=frame.city.astype(str).to_numpy()
    unique=sorted(set(cities[ids]))
    if len(unique)<3 or folds<2:
        raise ValueError("Need >=3 source-fit cities and >=2 folds")
    folds=min(int(folds),len(unique))
    x=np.concatenate((visual.detach().cpu().float().numpy(),
                      geo.detach().cpu().float().numpy()),axis=1)
    if not np.isfinite(x).all():
        raise ValueError("Nonfinite source visual inputs")
    labels=np.asarray(names,dtype=str)
    truth=y.detach().cpu().numpy() if isinstance(y,torch.Tensor) else np.asarray(y)
    out=np.full((len(frame),len(TRAIN_TASKS)),np.nan,dtype=np.float32)
    source_city=np.isin(cities,unique)
    for column,task in enumerate(TRAIN_TASKS):
        task_ids=ids[labels[ids]==task]
        groups=cities[task_ids]
        means,scale=stats[task]
        z=(truth[task_ids].astype(np.float64)-means)/scale
        splitter=GroupKFold(n_splits=folds)
        assigned=np.zeros(len(frame),dtype=bool)
        for fold,(fit,held) in enumerate(splitter.split(x[task_ids],z,groups)):
            train_cities=set(groups[fit])
            reserved=set(groups[held])
            if train_cities&reserved:
                raise AssertionError("Crossfit source city leakage")
            select=np.flatnonzero(np.isin(cities,list(reserved)))
            if len(fit)<2:
                raise ValueError("Not enough source labels for fold")
            reg=make_pipeline(StandardScaler(),
                              Ridge(alpha=alpha,solver="lsqr"))
            reg.fit(x[task_ids[fit]],z[fit])
            out[select,column]=np.asarray(
                reg.predict(x[select]),dtype=np.float32)
            assigned[select]=True
        if not np.array_equal(assigned,source_city):
            raise ValueError("OOF did not cover all source-fit city tiles")
        other=np.flatnonzero(~source_city)
        reg=make_pipeline(StandardScaler(),
                          Ridge(alpha=alpha,solver="lsqr"))
        reg.fit(x[task_ids],z)
        out[other,column]=np.asarray(reg.predict(x[other]),dtype=np.float32)
    if not np.isfinite(out).all():
        raise ValueError("Nonfinite OOF source indicator predictions")
    return torch.from_numpy(np.clip(out,-5.,5.))


def load_crossfit_context(frame,visual,geo,y,names,train_ids,stats,
                          manifest_path,cache_path,folds=4):
    path=Path(cache_path)
    manifest_path=Path(manifest_path).resolve()
    ids=np.asarray(train_ids,dtype=np.int64)
    value=y[torch.as_tensor(ids)].detach().cpu().numpy()
    digest=hashlib.sha256()
    digest.update(ids.tobytes())
    digest.update(value.tobytes())
    digest.update(json.dumps(stats,sort_keys=True).encode())
    metadata={
        "schema":"m67_oof_source_indicator_v1",
        "manifest_sha256":hashlib.sha256(manifest_path.read_bytes()).hexdigest(),
        "source_hash":digest.hexdigest(),"rows":len(frame),
        "visual_dim":visual.shape[-1],"folds":folds,
        "alpha":100.,"seed":42}
    if path.exists():
        saved=torch.load(path,map_location="cpu",weights_only=True)
        if saved.get("metadata")!=metadata:
            raise ValueError("M6.7 OOF context protocol mismatch")
        result=saved["predicted_source"]
        if result.shape!=(len(frame),2) or not bool(torch.isfinite(result).all()):
            raise ValueError("Corrupt M6.7 prediction cache")
        print(f"[m67] OOF source predictions HIT {path}",flush=True)
        return result
    print("[m67] fitting source-city 4-fold ridge predictions...",flush=True)
    result=crossfit_source_indicator_predictions(
        frame,visual,geo,y,names,ids,stats,folds=folds)
    path.parent.mkdir(parents=True,exist_ok=True)
    temp=path.with_name(path.name+".tmp")
    torch.save({"metadata":metadata,"predicted_source":result},temp)
    os.replace(temp,path)
    print(f"[m67] OOF source predictions SAVED {path}",flush=True)
    return result

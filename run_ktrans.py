"""K-TransMoE early prototype: K0 city/task meta splits + K1 semantic tasks."""
import argparse
from urban_transfer.data_paths import add_data_dir_argument, resolve_data_paths
from urban_transfer.ktrans import run, evaluate_meta
p=argparse.ArgumentParser()
add_data_dir_argument(p)
p.add_argument('command',choices=['train','evaluate-meta'])
for name in ('train','scui','ucsi','ucui'):
    p.add_argument('--'+name+'-csv')
p.add_argument('--image-root',default='/flash/project_462001391/xiyanxin/Urban_experience/output_files')
p.add_argument('--image-column')
p.add_argument('--feature-dir',default='runs/m3_features')
p.add_argument('--text-cache-dir',default='runs/ktrans_text_cache')
p.add_argument('--cache-dir',default='runs/qwen_cache')
p.add_argument('--remoteclip-model',choices=['ViT-B-32','ViT-L-14'],default='ViT-B-32')
p.add_argument('--remoteclip-checkpoint')
p.add_argument('--normalized-experts',action='store_true',help='K3-A source-only normalized spatial experts')
p.add_argument('--expert-bank',action='store_true',help='K2-B1 source-task experts with frozen semantic routing')
p.add_argument('--router-temperature',type=float,default=0.15)
p.add_argument('--scale-head',action='store_true',help='K2-A: task-conditioned affine output calibration')
p.add_argument('--task-encoder',choices=['hash','remoteclip','qwen3'],default='remoteclip')
p.add_argument('--text-model-id',default='Qwen/Qwen3-Embedding-0.6B')
p.add_argument('--task-profile',choices=['short','structured','llm'],default='short')
p.add_argument('--llm-profile-file')
p.add_argument('--heldout-task',default='digital_total_cell_intensity')
p.add_argument('--meta-city-fraction',type=float,default=0.2)
p.add_argument('--provider',default='no-llm')
p.add_argument('--limit',type=int,default=5000)
p.add_argument('--batch-size',type=int,default=128)
p.add_argument('--eval-batch-size',type=int,default=256)
p.add_argument('--eval-workers',type=int,default=0)
p.add_argument('--epochs',type=int,default=30)
p.add_argument('--patience',type=int,default=6)
p.add_argument('--lr',type=float,default=0.0001)
p.add_argument('--seed',type=int,default=42)
p.add_argument('--visual-dim',type=int,default=768)
p.add_argument('--hidden-dim',type=int,default=128)
p.add_argument('--experts',type=int,default=6)
p.add_argument('--top-k',type=int,default=2)
p.add_argument('--output',default='runs/ktrans_k1')
p.add_argument('--checkpoint')
args=resolve_data_paths(p.parse_args())
if args.command=='train':run(args)
else:evaluate_meta(args)

"""M3 independent entrypoint: precompute | train | evaluate."""
import argparse
from urban_transfer.m3 import extract,train,evaluate
p=argparse.ArgumentParser()
p.add_argument('command',choices=['precompute','train','evaluate'])
for k in ('train','scui','ucsi','ucui'):
    p.add_argument('--'+k+'-csv')
p.add_argument('--image-root',required=True)
p.add_argument('--image-column')
p.add_argument('--feature-dir',default='runs/m3_features')
p.add_argument('--remoteclip-model',choices=['ViT-B-32','ViT-L-14'],default='ViT-B-32')
p.add_argument('--remoteclip-checkpoint')
p.add_argument('--provider',choices=['no-llm','qwen3vl-latent','shuffled-latent'],default='no-llm')
p.add_argument('--model-id',default='Qwen/Qwen3-VL-2B-Instruct')
p.add_argument('--cache-dir',default='runs/qwen_cache')
p.add_argument('--no-cache',action='store_true')
p.add_argument('--output',default='runs/m3')
p.add_argument('--checkpoint')
p.add_argument('--resume')
p.add_argument('--batch-size',type=int,default=64,help='Precompute or training batch size')
p.add_argument('--eval-batch-size',type=int,default=256)
p.add_argument('--eval-workers',type=int,default=0,help='SQLite cache: default one reader process')
p.add_argument('--epochs',type=int,default=20)
p.add_argument('--patience',type=int,default=6)
p.add_argument('--lr',type=float,default=1e-4)
p.add_argument('--val-fraction',type=float,default=0.1)
p.add_argument('--limit',type=int)
p.add_argument('--seed',type=int,default=42)
p.add_argument('--task-dim',type=int,default=128)
p.add_argument('--visual-dim',type=int,default=768)
p.add_argument('--hidden-dim',type=int,default=128)
p.add_argument('--experts',type=int,default=6)
p.add_argument('--top-k',type=int,default=2)
args=p.parse_args()
if args.command=='precompute':extract(args)
elif args.command=='train':
    if not args.train_csv:p.error('--train-csv required for training')
    train(args)
else:evaluate(args)
